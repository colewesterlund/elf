#pragma once

#include <cstdint>

#include "BufferedEvent.h"
#include <deque>
#include <mutex>
#include <vector>
#include <atomic>

namespace elf {

// Thread-safe rolling in-memory buffer of recent events. Retention is governed
// by the global [buffer] retention_seconds from config.ini. The buffer is the
// source for both rule evaluation and `forward_buffer` actions.
//
// Cumulative counters track every event the host has generated (pushed into
// the buffer) and the total bytes of XML. These are reported to the server on
// each poll so the UI can show the fraction of events that were actually
// forwarded vs. created by the host.
class EventBuffer {
public:
    // Add a rendered event to the buffer, stamped with the current time.
    void push(const std::wstring& xml);

    // Add a rendered event with an explicit arrival time. Used by tests to
    // drive correlation windows deterministically (e.g. "a 4625 that
    // arrived 200 s ago"); the live collector uses the one-argument form.
    void push(const std::wstring& xml, std::chrono::system_clock::time_point receivedAt);

    // Drop events older than retention_seconds. Called periodically by a
    // cleanup thread.
    void cleanup(int retentionSeconds);

    // Drop oldest events until the buffer holds at most `maxEvents` entries.
    // Called after push() when max_events is configured, to bound RAM on
    // very busy hosts regardless of the retention window.
    void trimTo(size_t maxEvents);

    // Snapshot the entire current buffer (used by forward_buffer actions and
    // by the rule engine when it needs a stable view).
    std::vector<BufferedEvent> snapshot() const;

    // Snapshot events from index `from` onward, returning them as mutable
    // copies. `total` is set to the current buffer size. Used by the rule
    // engine to process only newly-arrived events each pass.
    std::vector<BufferedEvent> snapshotFrom(size_t from, size_t& total) const;

    // Snapshot events from absolute index `absFrom` onward, where `absFrom` is
    // a position in the cumulative event stream (i.e. an index that accounts
    // for events popped from the front by cleanup/trimTo). `absEnd` is set to
    // the absolute index just past the newest event in the snapshot, the
    // value the caller should use as its next `absFrom`. It is computed
    // under the same lock as the snapshot, so events popped by the cleanup
    // thread while the caller is still processing the snapshot can never
    // shift it (a `frontPopped() + size` formula evaluated after the pass
    // would skip exactly as many new events as cleanup popped during the
    // pass). Returns empty if `absFrom` is at or past the newest
    // event. If `absFrom` is below the oldest surviving event, the gap is
    // counted in evictedUnevaluated(); those events were dropped before
    // the engine ever saw them.
    // `trackEvicted` is false for non-evaluation readers (a forward_buffer
    // cursor) so they don't inflate the counter.
    std::vector<BufferedEvent> snapshotFromAbsolute(uint64_t absFrom, uint64_t& absEnd,
                                                    bool trackEvicted = true) const;

    // Number of events popped from the front of the deque since the buffer
    // was created (by cleanup() and trimTo()). Used by the rule engine to
    // convert its absolute (pop-stable) cursor into a live deque index.
    uint64_t frontPopped() const { return m_frontPopped.load(); }

    // Events that were evicted (retention/trim) before any evaluation pass
    // snapshotted them. A non-zero, growing value means the engine is not
    // keeping up with the event rate (or retention is too short) and
    // alerts are being missed; the status thread reports it.
    uint64_t evictedUnevaluated() const { return m_evictedUnevaluated.load(); }

    size_t size() const;

    // Cumulative counters since agent start. eventsCreated is the total
    // number of Windows events pushed into the buffer (i.e. generated by the
    // host). bytesCreated is the total UTF-8 byte length of those event XML
    // strings. These never reset and are reported to the server on each poll.
    uint64_t eventsCreated() const { return m_eventsCreated.load(); }
    uint64_t bytesCreated() const { return m_bytesCreated.load(); }

private:
    mutable std::mutex m_mutex;
    std::deque<BufferedEvent> m_events;
    std::atomic<uint64_t> m_eventsCreated{0};
    std::atomic<uint64_t> m_bytesCreated{0};
    // Cumulative count of events popped from the front (by cleanup/trimTo).
    // Lets callers convert a live deque index into an absolute stream index
    // that survives front pops. Atomic because it is read by the rule engine
    // thread without the buffer mutex.
    std::atomic<uint64_t> m_frontPopped{0};
    mutable std::atomic<uint64_t> m_evictedUnevaluated{0};
};

} // namespace elf
