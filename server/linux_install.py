"""Install and cleanup scripts for Linux hosts (the Add New Agent dialog).

The console hands the operator a bash script to run with sudo on the target
host. It does for Linux what the PowerShell script does for Windows:
download the agent from the console, provision a least-privilege service
account, write the config, register the agent, install and start the
systemd unit. No internet access is needed on the target.
"""

import re

# Linux usernames as useradd accepts them (also keeps the generated bash
# free of quoting surprises).
_USERNAME = re.compile(r"^[a-z_][a-z0-9_-]{0,31}\$?$")

DEFAULT_SERVICE_USER = "elf"

# Written to /etc/elf/config.ini. __AGENT_ID__ / __AUTH_TOKEN__ are filled
# in by the script at install time; the base URL is known when generating.
_CONFIG_INI = """[buffer]
retention_seconds=30

[rules]
directory=/var/lib/elf/rules

[lists]
directory=/var/lib/elf/lists

[server]
url=__BASE__
poll_interval_seconds=30
agent_id=__AGENT_ID__
auth_token=__AUTH_TOKEN__

[logging]
level=notice
max_file_size_mb=1
max_files=3
directory=/var/lib/elf/logs

[spool]
max_spool_mb=100
directory=/var/lib/elf/spool

[destinations]
siem = file:///var/lib/elf/output/siem.jsonl
data_lake = file:///var/lib/elf/output/data_lake.jsonl
alerts = file:///var/lib/elf/output/alerts.jsonl
"""

# The systemd unit. The agent writes only under /var/lib/elf; everything
# else is read-only to it. Reading the journal needs the systemd-journal
# group, which the script adds the account to.
_UNIT = """[Unit]
Description=Efficient Log Forwarder agent
After=network-online.target systemd-journald.service
Wants=network-online.target

[Service]
Type=simple
User=__USER__
Group=__GROUP__
SupplementaryGroups=systemd-journal
Environment=ELF_CONFIG=/etc/elf/config.ini
ExecStart=/opt/elf/elf-agent
Restart=on-failure
RestartSec=30
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
ReadWritePaths=/var/lib/elf
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictRealtime=yes

[Install]
WantedBy=multi-user.target
"""

# Audit rules that record every program execution, so the process_creation
# rules have something to evaluate. Installed only when the operator asks.
_AUDIT_RULES = """## ELF: record program executions (key elf_exec)
-a always,exit -F arch=b64 -S execve,execveat -k elf_exec
-a always,exit -F arch=b32 -S execve,execveat -k elf_exec
"""


def validate_linux_username(username: str) -> str:
    """The username of an existing account to run the service as."""
    u = username.strip()
    if not _USERNAME.match(u):
        raise ValueError(
            "Linux username: lowercase letters, digits, dot, dash and "
            "underscore, starting with a letter or underscore."
        )
    return u


def build_install_sh(base: str, group: str, group_id: int,
                     account_mode: str, username: str, audit_execve: bool) -> str:
    """The install script for one host.

    account_mode 'local' creates a dedicated system user (no shell, no
    home); 'existing' runs the service as an account that already exists
    on the host, which only gains the systemd-journal group membership.
    """
    if account_mode == "existing":
        svc_user = validate_linux_username(username)
        account_note = f"existing account '{svc_user}'"
    else:
        svc_user = DEFAULT_SERVICE_USER
        account_note = f"dedicated system user '{svc_user}' (created if missing)"
    base_q = base.replace("'", "")
    group_q = group.replace("'", "")

    s = f"""#!/bin/bash
# ==========================================================================
# ELF Agent install script (Linux)
# Generated by the ELF management server for group '{group_q}'.
#
# Paste the whole text into a shell on the target host, or save it and run
# it with bash. It asks for your sudo password once, then:
#   1. Downloads the agent from the management server.
#   2. Provisions the service account: {account_note}.
#   3. Creates the state tree under /var/lib/elf, owned by that account.
#   4. Registers the agent with the server and receives its auth token.
#   5. Writes /etc/elf/config.ini with agent_id = this host's name.
#   6. Installs and starts the systemd unit (starts at boot, restarts on failure).
# ==========================================================================
# Everything below runs in one root shell, so a paste into an interactive
# session is collected first and run as a unit, and an error ends the
# install, not your login session.
if [ "$(id -u)" -eq 0 ]; then ELF_SUDO=''; else ELF_SUDO='sudo'; fi
$ELF_SUDO bash -s <<'ELF_INSTALL'
set -euo pipefail
BASE='{base_q}'
GROUP='{group_q}'
GROUP_ID={int(group_id)}
SVC_USER='{svc_user}'
UNIT=elf-agent
AGENT_ID="$(hostname -s)"

if [ "$(id -u)" -ne 0 ]; then echo "This script needs root (sudo)." >&2; exit 1; fi
for t in curl systemctl install useradd usermod; do
  command -v "$t" >/dev/null 2>&1 || {{ echo "Missing command: $t" >&2; exit 1; }}
done

# --- 1. Download the agent ------------------------------------------------
# Stop a running agent first so the binary can be replaced.
systemctl stop "$UNIT" 2>/dev/null || true
install -d -m 0755 /opt/elf /etc/elf
TMP="$(mktemp)"
echo "Downloading the agent from $BASE ..."
curl -fsSL "$BASE/agent/binary?os=linux" -o "$TMP"
install -m 0755 "$TMP" /opt/elf/elf-agent
rm -f "$TMP"
/opt/elf/elf-agent --version

# --- 2. Service account -----------------------------------------------------
"""
    if account_mode == "existing":
        s += """if ! id -u "$SVC_USER" >/dev/null 2>&1; then
  echo "The account $SVC_USER does not exist on this host." >&2
  exit 1
fi
"""
    else:
        s += """if ! id -u "$SVC_USER" >/dev/null 2>&1; then
  useradd --system --no-create-home --shell /usr/sbin/nologin --user-group "$SVC_USER"
  echo "Created system user $SVC_USER."
fi
"""
    s += """# Reading the journal needs membership in systemd-journal.
usermod -aG systemd-journal "$SVC_USER"
SVC_GROUP="$(id -gn "$SVC_USER")"

# --- 3. State tree ------------------------------------------------------------
# Logs, spool, cursor, server-pushed rules and lists, file destinations.
install -d -m 0750 -o "$SVC_USER" -g "$SVC_GROUP" /var/lib/elf
for sub in logs spool state rules lists output; do
  install -d -m 0750 -o "$SVC_USER" -g "$SVC_GROUP" "/var/lib/elf/$sub"
done

# --- 4. Register with the management server -----------------------------------
# The server mints an enrollment token for this agent; it goes into
# config.ini so the agent can authenticate on its first poll.
AUTH_TOKEN=""
RESP="$(curl -fsS -X POST "$BASE/agents/register" -H 'Content-Type: application/json' \\
  -d "{\\"agent_id\\":\\"$AGENT_ID\\",\\"hostname\\":\\"$(hostname)\\",\\"group_id\\":$GROUP_ID}" || true)"
AUTH_TOKEN="$(printf '%s' "$RESP" | grep -o '"auth_token":"[^"]*"' | cut -d'"' -f4 || true)"
if [ -z "$AUTH_TOKEN" ]; then
  echo "Warning: could not register with the server. The agent registers itself" >&2
  echo "on first contact; you may need to approve it in the UI." >&2
fi

# --- 5. config.ini ----------------------------------------------------------------
cat > /etc/elf/config.ini <<'EOF'
""" + _CONFIG_INI.replace("__BASE__", base_q) + """EOF
sed -i "s|__AGENT_ID__|$AGENT_ID|; s|__AUTH_TOKEN__|$AUTH_TOKEN|" /etc/elf/config.ini
chown root:"$SVC_GROUP" /etc/elf/config.ini
chmod 0640 /etc/elf/config.ini

# --- 6. systemd unit ----------------------------------------------------------------
cat > /etc/systemd/system/elf-agent.service <<'EOF'
""" + _UNIT.replace("__USER__", svc_user).replace("__GROUP__", "__GROUP_PLACEHOLDER__") + """EOF
sed -i "s|__GROUP_PLACEHOLDER__|$SVC_GROUP|" /etc/systemd/system/elf-agent.service
systemctl daemon-reload
systemctl enable --now "$UNIT"
"""
    if audit_execve:
        s += """
# --- 7. Audit rule for process execution ---------------------------------------
# Records every execve so the process_creation rules have events. journald
# receives the audit stream alongside auditd through its audit socket,
# which Debian and Ubuntu leave disabled by default.
install -d /etc/systemd/journald.conf.d
printf '[Journal]\\nAudit=yes\\n' > /etc/systemd/journald.conf.d/elf-audit.conf
# The socket cannot start while journald runs; the restart brings it up.
systemctl unmask systemd-journald-audit.socket >/dev/null 2>&1 || true
systemctl enable systemd-journald-audit.socket
systemctl restart systemd-journald
if command -v auditctl >/dev/null 2>&1; then
  install -d /etc/audit/rules.d
  cat > /etc/audit/rules.d/elf-execve.rules <<'EOF'
""" + _AUDIT_RULES + """EOF
  augenrules --load >/dev/null 2>&1 || auditctl -R /etc/audit/rules.d/elf-execve.rules >/dev/null 2>&1 || true
  echo "Audit rule for program execution installed (key elf_exec)."
else
  echo "auditd is not installed; the execve audit rule was skipped." >&2
  echo "Install auditd (apt install auditd / dnf install audit) and re-run this script." >&2
fi
"""
    s += """
echo ""
echo "ELF agent installed as unit $UNIT and started as $AGENT_ID (group: $GROUP)."
echo "  Account: $SVC_USER (systemd-journal)   Config: /etc/elf/config.ini"
echo "  Data: /var/lib/elf   Log: /var/lib/elf/logs/elf_agent.log"
echo "  Status: systemctl status $UNIT"
ELF_INSTALL
"""
    return s


CLEANUP_SH = """#!/bin/bash
# ==========================================================================
# ELF Agent cleanup script (Linux)
# Paste the whole text into a shell on the host, or save it and run it
# with bash; it asks for your sudo password once. Removes everything the
# install script created: the systemd unit, /opt/elf, /etc/elf,
# /var/lib/elf, the audit rule and journald drop-in, and the dedicated
# 'elf' system user. An existing account that was chosen as the service
# account is left in place. Safe to run more than once, and when nothing
# is installed.
# ==========================================================================
if [ "$(id -u)" -eq 0 ]; then ELF_SUDO=''; else ELF_SUDO='sudo'; fi
$ELF_SUDO bash -s <<'ELF_CLEANUP'
set -u
if [ "$(id -u)" -ne 0 ]; then echo "This script needs root (sudo)." >&2; exit 1; fi
echo "=== ELF Agent cleanup ==="
systemctl disable --now elf-agent 2>/dev/null || true
rm -f /etc/systemd/system/elf-agent.service
systemctl daemon-reload
rm -rf /opt/elf /etc/elf /var/lib/elf
if [ -f /etc/audit/rules.d/elf-execve.rules ]; then
  rm -f /etc/audit/rules.d/elf-execve.rules
  augenrules --load >/dev/null 2>&1 || true
  echo "  removed the audit rule"
fi
if [ -f /etc/systemd/journald.conf.d/elf-audit.conf ]; then
  rm -f /etc/systemd/journald.conf.d/elf-audit.conf
  systemctl restart systemd-journald 2>/dev/null || true
fi
# Only the dedicated system account (no login shell) is deleted.
if id -u elf >/dev/null 2>&1; then
  shell="$(getent passwd elf | cut -d: -f7)"
  case "$shell" in
    */nologin|*/false) userdel elf 2>/dev/null && echo "  removed user elf" ;;
    *) echo "  kept user elf (it has a login shell, so it was not created by the install script)" ;;
  esac
fi
echo "Done."
ELF_CLEANUP
"""
